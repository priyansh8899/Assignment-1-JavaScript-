// Write a program to take two string numbers and perform numeric addition after conversion.

let str1:string = "350";
let str2:string = "150";

let num1:number = Number(str1);
let num2:number = Number(str2);

let add = num1 + num2;

console.log(`Number 1 :- ${num1}`);
console.log(`Number 1 :- ${num1}`);
console.log(`Addition of ${num1} + ${num2} :- ${add}`);

