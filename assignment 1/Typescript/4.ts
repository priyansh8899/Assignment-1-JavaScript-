//Write a program to store one number and find its square and cube.

let num:number = 6;
let sq:number = num * num;
let cube:number = num * num * num;

console.log(`Number :- ${num}`);
console.log(`Square of ${num} :- ${sq}`);
console.log(`Cube of ${num} :- ${cube}`);

/* Number :- 6
Square of 6 :- 36
Cube of 6 :- 216 */